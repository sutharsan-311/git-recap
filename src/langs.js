export function extOf(path) {
  const base = path.split('/').pop() || path;
  const i = base.lastIndexOf('.');
  if (i <= 0) return null;
  return base.slice(i + 1).toLowerCase();
}

export function langOf(path) {
  const ext = extOf(path);
  if (!ext) return null;
  const hit = LANGS[ext];
  return hit ? { name: hit[0], color: hit[1] } : null;
}
